package com.oracle.svm.hosted.foreign;

import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;

import com.oracle.graal.pointsto.infrastructure.SubstitutionProcessor;
import com.oracle.graal.pointsto.meta.BaseLayerType;
import com.oracle.svm.hosted.annotation.CustomSubstitutionType;
import com.oracle.svm.shared.util.VMError;
import com.oracle.svm.util.OriginalClassProvider;

import jdk.vm.ci.meta.MetaUtil;
import jdk.vm.ci.meta.ResolvedJavaType;

/**
 * Renames the hidden classes generated by the JDK specialized FFM upcall implementation. The host
 * VM appends a run-specific suffix to hidden class names, so they need an explicitly registered
 * semantic name to be identifiable across image builds.
 */
final class UpcallStubRenamingSubstitutionProcessor extends SubstitutionProcessor {
    private static final String UPCALL_STUB_CLASS_NAME_PREFIX = "jdk.internal.foreign.abi.UpcallStub/";

    private final ConcurrentMap<Class<?>, String> stableNames = new ConcurrentHashMap<>();
    private final ConcurrentMap<ResolvedJavaType, UpcallStubSubstitutionType> typeSubstitutions = new ConcurrentHashMap<>();

    void register(Class<?> upcallStubClass, String stableName) {
        VMError.guarantee(stableName.endsWith(";") && MetaUtil.internalNameToJava(stableName, true, true).startsWith(UPCALL_STUB_CLASS_NAME_PREFIX),
                        "Invalid stable upcall stub name: %s", stableName);
        String previous = stableNames.putIfAbsent(upcallStubClass, stableName);
        VMError.guarantee(previous == null || previous.equals(stableName), "Conflicting stable names for upcall stub %s: %s and %s", upcallStubClass, previous, stableName);
    }

    @Override
    public ResolvedJavaType lookup(ResolvedJavaType type) {
        if (type instanceof UpcallStubSubstitutionType || type instanceof BaseLayerType || !type.toClassName().startsWith(UPCALL_STUB_CLASS_NAME_PREFIX)) {
            return type;
        }
        VMError.guarantee(type.isHidden(), "Expected a hidden upcall stub class: %s", type);
        String stableName = stableNames.get(OriginalClassProvider.getJavaClass(type));
        if (stableName == null) {
            return type;
        }
        return typeSubstitutions.computeIfAbsent(type, original -> new UpcallStubSubstitutionType(original, stableName));
    }
}

/** Substitution type that exposes a caller-supplied stable name for a generated upcall stub. */
final class UpcallStubSubstitutionType extends CustomSubstitutionType {
    private final String stableName;

    UpcallStubSubstitutionType(ResolvedJavaType original, String stableName) {
        super(original);
        this.stableName = stableName;
    }

    @Override
    public String getName() {
        return stableName;
    }
}
