package com.oracle.truffle.api.bytecode;

/**
 * Configures how a generated bytecode interpreter makes its current bytecode index available for
 * stack walking and frame introspection.
 *
 * @see GenerateBytecode#bytecodeIndexMode()
 * @since 25.6
 */
public enum BytecodeIndexMode {

    /**
     * Stores the current bytecode index automatically in the frame in all interpreter tiers. The
     * stored index can also be read or updated manually using {@link BytecodeNode#getBytecodeIndex}
     * and {@link BytecodeNode#setBytecodeIndex}. A manual value persists until the next automatic
     * update. Implicit stack-frame lookup still requires a non-null location node.
     *
     * @since 25.6
     */
    FRAME,

    /**
     * Derives the bytecode index from the current operation node in the cached interpreter and
     * stores it automatically in the frame in the uncached interpreter. This is the default mode.
     * The frame slot is an implementation detail and cannot be accessed using
     * {@link BytecodeNode#getBytecodeIndex} or
     * {@link BytecodeNode#setBytecodeIndex}.
     *
     * @since 25.6
     */
    CACHED_NODE,

    /**
     * Reserves a frame slot that is updated manually using {@link BytecodeNode#setBytecodeIndex} or
     * explicitly for operations using {@link Operation#storeBytecodeIndex()} or
     * {@link StoreBytecodeIndex}. Automatic operation storage is disabled by default. The stored
     * index can be read using {@link BytecodeNode#getBytecodeIndex} and is used for implicit
     * stack-frame lookup even when no location node is available. The slot is not initialized on a
     * fresh invocation. Once stored, the index is preserved across tier transitions and translated
     * when the bytecode layout changes during execution. Resuming a continuation always replaces
     * the stored value with the resume bytecode index, even if the value was unset or cleared.
     *
     * @since 25.6
     */
    MANUAL,

    /**
     * Does not reserve a frame slot or perform implicit bytecode index lookup. Bytecode indices
     * must be passed explicitly to calls, exceptions, and other APIs that require them.
     *
     * @since 25.6
     */
    NONE,
}
